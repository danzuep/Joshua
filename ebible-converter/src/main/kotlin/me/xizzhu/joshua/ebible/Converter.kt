package me.xizzhu.joshua.ebible

import java.io.File
import java.io.InputStream
import java.io.OutputStream
import java.util.zip.ZipEntry
import java.util.zip.ZipInputStream
import java.util.zip.ZipOutputStream

data class TranslationMeta(val shortName: String, val name: String, val language: String)

/** Reads a USFM zip (as downloaded from ebible.org) into books keyed by USFM code. */
fun readUsfmZip(input: InputStream): Map<String, UsfmBook> {
    val books = hashMapOf<String, UsfmBook>()
    ZipInputStream(input).use { zip ->
        generateSequence { zip.nextEntry }.forEach { entry ->
            val entryName = entry.name.lowercase()
            if (!entry.isDirectory && (entryName.endsWith(".usfm") || entryName.endsWith(".sfm"))) {
                val book = parseUsfm(zip.readBytes().toString(Charsets.UTF_8))
                if (book.code in BOOK_CODES) books[book.code] = book
            }
        }
    }
    return books
}

/** Writes Joshua's `translations/<shortName>.zip` content: books.json plus `<book>-<chapter>.json` (0-based). */
fun writeJoshuaZip(books: Map<String, UsfmBook>, meta: TranslationMeta, output: OutputStream) {
    val missing = BOOK_CODES.filter { it !in books }
    require(missing.isEmpty()) { "Joshua requires all 66 books; missing: ${missing.joinToString(" ")}" }

    ZipOutputStream(output).use { zip ->
        fun put(name: String, json: String) {
            zip.putNextEntry(ZipEntry(name))
            zip.write(json.toByteArray(Charsets.UTF_8))
            zip.closeEntry()
        }

        val names = BOOK_CODES.map { books.getValue(it).name ?: it }.joinToString(",", "[", "]") { it.json() }
        put("books.json", """{"name":${meta.name.json()},"shortName":${meta.shortName.json()},""" +
                """"language":${meta.language.json()},"bookNames":$names,"bookShortNames":$names}""")

        BOOK_CODES.forEachIndexed { bookIndex, code ->
            for (chapter in 1..CHAPTER_COUNTS[bookIndex]) {
                val verses = requireNotNull(books.getValue(code).chapters[chapter]?.takeIf { it.isNotEmpty() }) { "$code $chapter has no verses" }
                // Gaps (e.g. verses omitted by a critical text) become empty strings to keep numbering aligned.
                val texts = (1..verses.keys.max()).joinToString(",", "[", "]") { (verses[it] ?: "").json() }
                put("$bookIndex-${chapter - 1}.json", """{"verses":$texts}""")
            }
        }
    }
}

/** Converts [source] and merges the result into `<out>/list.json`. */
fun convert(source: File, meta: TranslationMeta, out: File) {
    val zipFile = File(out, "translations/${meta.shortName}.zip").apply { parentFile.mkdirs() }
    source.inputStream().buffered().use { input ->
        zipFile.outputStream().buffered().use { output -> writeJoshuaZip(readUsfmZip(input), meta, output) }
    }

    val listFile = File(out, "list.json")
    val existing = if (listFile.exists()) existingEntries(listFile.readText()) else emptyList()
    val entry = """{"shortName":${meta.shortName.json()},"name":${meta.name.json()},""" +
            """"language":${meta.language.json()},"size":${zipFile.length()}}"""
    listFile.writeText((existing.filterNot { it.shortName == meta.shortName }.map { it.raw } + entry)
            .joinToString(",\n  ", "{\"translations\": [\n  ", "\n]}\n"))
}

private class ListEntry(val shortName: String, val raw: String)

// list.json is flat and generated by this tool or the upstream author, so a light regex split is enough.
private fun existingEntries(text: String): List<ListEntry> =
        Regex("""\{[^{}]*\}""").findAll(text.substringAfter('[')).map { it.value }.mapNotNull { raw ->
            Regex(""""shortName"\s*:\s*"((?:[^"\\]|\\.)*)"""").find(raw)?.let { ListEntry(it.groupValues[1], raw) }
        }.toList()

internal fun String.json(): String = buildString {
    append('"')
    for (c in this@json) when {
        c == '"' -> append("\\\"")
        c == '\\' -> append("\\\\")
        c < ' ' -> append("\\u%04x".format(c.code))
        else -> append(c)
    }
    append('"')
}
